#!/usr/bin/env python3
"""Collect published dependency notices; --check is offline and needs no Cargo cache.

Regeneration requires Python 3.11+, `cargo fetch --locked`, and internet access for crates whose
published archives omit license files. Upstream requests use the published VCS
commit; standard CC0/MITNFA texts use a pinned SPDX license-list release.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "apps/cli/packaging/THIRD-PARTY-LICENSES.txt"
HEADER = "Cargo.lock SHA-256: "
LICENSE_NAME = re.compile(r"^(?:licen[cs]e|copying|notice|copyright|authors)(?:[._-].*)?$", re.I)
REMOTE_CACHE = {}


def download(url):
    if url not in REMOTE_CACHE:
        try:
            with urllib.request.urlopen(url, timeout=30) as response:
                REMOTE_CACHE[url] = response.read().decode("utf-8")
        except urllib.error.HTTPError as error:
            if error.code != 404:
                raise
            REMOTE_CACHE[url] = None
    return REMOTE_CACHE[url]


def materials(directory, metadata):
    files = {}
    for path in sorted(directory.rglob("*")):
        if (path.is_file() and LICENSE_NAME.fullmatch(path.name)
                and path.suffix not in {".rs", ".c", ".h", ".py", ".go"}):
            files[str(path.relative_to(directory))] = path.read_text(encoding="utf-8")
    explicit = metadata.get("license-file")
    if explicit:
        path = (directory / explicit).resolve()
        if not path.is_relative_to(directory.resolve()) or not path.is_file():
            raise ValueError(f"Invalid packaged license-file: {directory.name}")
        files[explicit] = path.read_text(encoding="utf-8")
    if files:
        return files
    spdx = metadata.get("license", "")
    if spdx in {"CC0-1.0", "MITNFA"}:
        url = f"https://raw.githubusercontent.com/spdx/license-list-data/v3.27.0/text/{spdx}.txt"
        text = download(url)
        if not text:
            raise ValueError(f"Missing standard license: {spdx}")
        return {url: text}
    vcs = directory / ".cargo_vcs_info.json"
    if vcs.exists():
        revision = json.loads(vcs.read_text())["git"]["sha1"]
        repository = metadata["repository"].removesuffix(".git").rstrip("/")
        if not repository.startswith("https://github.com/") or not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise ValueError(f"Review upstream license source: {directory.name}")
        base = repository.replace("https://github.com/", "https://raw.githubusercontent.com/")
        for name in ("LICENSE", "LICENSE.md", "LICENSE-MIT", "LICENSE-APACHE", "COPYING", "NOTICE"):
            url = f"{base}/{revision}/{name}"
            text = download(url)
            if text:
                files[url] = text
    elif metadata["name"].startswith("winapi-"):
        # Import-library crates omit the notices shipped by the same winapi release.
        sibling = directory.parent / "winapi-0.3.9"
        for name in ("LICENSE-MIT", "LICENSE-APACHE"):
            files[f"winapi-0.3.9/{name}"] = (sibling / name).read_text()
    if not files:
        raise ValueError(f"No license material found; review {directory.name}")
    return files


def generate(packages, digest):
    import tomllib
    cache = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")) / "registry/src"
    result = ["TermKey third-party licenses and notices", HEADER + digest,
              "Generated by scripts/generate-third-party-licenses.py; do not edit.",
              "Includes all registry packages in Cargo.lock, including optional/build/test dependencies.",
              "Not every listed component is present in every platform executable.", ""]
    texts = {}
    for package in sorted(packages, key=lambda p: (p["name"], p["version"])):
        name = package["name"] + " " + package["version"]
        directories = sorted(cache.glob("*/" + package["name"] + "-" + package["version"]))
        if not directories:
            raise ValueError(f"Missing source for {name}; run cargo fetch --locked")
        directory = directories[0]
        metadata = tomllib.loads((directory / "Cargo.toml").read_text())["package"]
        result += ["=" * 72, name, "Registry checksum: " + package["checksum"],
                   "Declared license: " + metadata.get("license", "see license-file"),
                   "Authors: " + "; ".join(metadata.get("authors", []))]
        # Retain attribution notices from source headers as well as standalone files.
        copyrights = set()
        for path in directory.rglob("*"):
            if path.is_file() and path.suffix in {".rs", ".c", ".h", ".cpp", ".S"}:
                for line in path.read_text(errors="replace").splitlines()[:40]:
                    if re.search(r"copyright\s*(?:\(c\)|©|[0-9])", line, re.I):
                        copyrights.add(line.strip().lstrip("/*# ").rstrip("*/ "))
        result.extend(sorted(copyrights))
        for source, text in materials(directory, metadata).items():
            normalized = text.replace("\r\n", "\n").strip() + "\n"
            key = hashlib.sha256(normalized.encode()).hexdigest()
            texts[key] = normalized
            result += ["License source: " + source, "License text: " + key]
        result.append("")
    result += ["=" * 72, "LICENSE TEXTS (identical texts shared by reference)", ""]
    for key, text in sorted(texts.items()):
        result += ["License text: " + key, text]
    return "\n".join(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lock = (ROOT / "Cargo.lock").read_bytes()
    digest = hashlib.sha256(lock).hexdigest()
    # Cargo's generated lockfile uses simple quoted strings for these fields.
    # Keep offline --check usable with the Python 3.9+ shipped on macOS runners.
    packages = []
    for block in lock.decode().split("[[package]]")[1:]:
        package = {key: json.loads(value) for key, value in re.findall(
            r'^(name|version|source|checksum) = ("[^"\n]*")$', block, re.M)}
        if package.get("source", "").startswith("registry+"):
            packages.append(package)
    if args.check:
        text = OUTPUT.read_text()
        if HEADER + digest not in text.splitlines():
            raise ValueError("Third-party notices are stale; regenerate after Cargo.lock changes")
        for package in packages:
            if package["name"] + " " + package["version"] not in text.splitlines():
                raise ValueError("Third-party notices omit a locked dependency")
            if "Registry checksum: " + package["checksum"] not in text.splitlines():
                raise ValueError("Third-party notices do not match dependency checksums")
        marker = "LICENSE TEXTS (identical texts shared by reference)\n\n"
        if marker not in text:
            raise ValueError("Third-party license texts are missing")
        attribution, license_texts = text.split(marker, 1)
        chunks = re.split(r"^License text: ([0-9a-f]{64})\n", license_texts, flags=re.M)
        available = set()
        for index in range(1, len(chunks), 2):
            key, body = chunks[index:index + 2]
            if hashlib.sha256((body.strip() + "\n").encode()).hexdigest() != key:
                raise ValueError("Third-party license text is truncated or modified")
            available.add(key)
        required = set(re.findall(r"^License text: ([0-9a-f]{64})$", attribution, re.M))
        if not required or required != available:
            raise ValueError("Third-party license text references are incomplete")
        print(f"Third-party notices match {len(packages)} locked dependencies")
    else:
        OUTPUT.write_text(generate(packages, digest))
        print(f"Generated notices for {len(packages)} locked dependencies: {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError) as error:
        print(f"License generation failed: {error}", file=sys.stderr)
        sys.exit(1)
